#!/usr/bin/env python3
"""Install the pinned Humaneness Voice assets into a portable directory.

This intentionally does not download the 97.6 GB reference dataset wholesale.
Run fetch_profile_refs.py for the selected speaker(s) after this step.
"""
import argparse
import json
import os
from pathlib import Path
import shlex

from huggingface_hub import snapshot_download


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / "manifests/agent-default-v1.json").read_text())
ASSETS = MANIFEST["assets"]
DATA = Path(os.environ.get("HUMANENESS_DATA_DIR") or os.environ.get(
    "MOSS_DATA_DIR", "~/.cache/humaneness-voice")).expanduser().resolve()
LORAS = Path(os.environ.get("MOSS_ASSETS", DATA / "loras")).expanduser().resolve()


def fetch(key, destination=None, patterns=None, check=False):
    spec = ASSETS[key]
    kw = {"repo_id": spec["repo"], "revision": spec["revision"],
          "repo_type": spec["type"]}
    if destination is not None:
        kw["local_dir"] = str(destination)
    if patterns is not None:
        kw["allow_patterns"] = patterns
    if check:
        kw["local_files_only"] = True
    try:
        path = snapshot_download(**kw)
        print(f"{'ready' if check else 'fetched':8} {key:20} {path}")
        return path
    except Exception as exc:
        print(f"{'missing' if check else 'FAILED':8} {key:20} {type(exc).__name__}: {exc}")
        return None


def adapter_files(names):
    return [f"{name}/{file}" for name in names
            for file in ("adapter_config.json", "adapter_model.safetensors",
                         "bucket.json", "RECOMMENDED.json")]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="inspect installed assets without downloading")
    ap.add_argument("--minimal", action="store_true", help="base, codec, one voice, one emotion and preference DPO only")
    ap.add_argument("--profile", action="append", choices=MANIFEST["pilot_profiles"],
                    help="speaker to install; repeat for more than one")
    ap.add_argument("--all-profiles", action="store_true", help="install all ten tested pilot voices")
    ap.add_argument("--director", action="store_true", help="also download the local director GGUF files")
    args = ap.parse_args()
    profiles = MANIFEST["pilot_profiles"] if args.all_profiles else (
        args.profile or [MANIFEST["default_profile"]])
    failures = []

    def get(key, destination=None, patterns=None):
        path = fetch(key, destination, patterns, args.check)
        if path is None:
            failures.append(key)
        return path

    base = get("base")
    codec = get("codec")
    get("preference_dpo", LORAS / "sft3_dpo" / "p2",
        ["adapter_config.json", "adapter_model.safetensors"])
    get("voice_adapters", LORAS / "sft3_voice", adapter_files(profiles))
    emotions = ["Relief"] if args.minimal else None
    get("emotion_adapters", LORAS / "sft3_emotion",
        adapter_files(emotions) if emotions else
        ["*/adapter_config.json", "*/adapter_model.safetensors"])

    voiceclap = asr = aligner = None
    if not args.minimal:
        get("quality_dpo", LORAS / "sft3_qdpo" / "quality_dpo",
            ["adapter_config.json", "adapter_model.safetensors"])
        for key, folder in (("quality_adapters", "sft3_quality"),
                            ("delivery_adapters", "sft3_voicenet"),
                            ("burst_adapters", "burst")):
            get(key, LORAS / folder,
                ["adapters/*/adapter_config.json",
                 "adapters/*/adapter_model.safetensors", "manifest.json"])
        voiceclap = get("voiceclap")
        get("genuineness_head", DATA / "scorers" / "genuineness")
        get("blend_head", DATA / "scorers" / "blend")
        asr = get("asr")
        aligner = get("aligner")
    if args.director:
        get("director", DATA / "director",
            ["*Q4_K_XL.gguf", "mmproj-F16.gguf"])

    if not args.check and base and codec:
        # Generated paths pin the exact snapshots. They contain no credentials.
        target = ROOT / ".env.generated"
        lines = ["# Generated by setup/fetch_all.py; do not edit or commit.",
                 f"export MOSS_DATA_DIR={shlex.quote(str(DATA))}",
                 f"export MOSS_ASSETS={shlex.quote(str(LORAS))}",
                 f"export MOSS_TTS_REPO={shlex.quote(str(base))}",
                 f"export MOSS_CODEC_REPO={shlex.quote(str(codec))}"]
        for name, path in (("MOSS_VOICECLAP", voiceclap),
                           ("MOSS_ASR_MODEL", asr),
                           ("MOSS_ALIGN_QWEN", aligner)):
            if path:
                lines.append(f"export {name}={shlex.quote(str(path))}")
        target.write_text("\n".join(lines) + "\n", encoding="utf-8")
        target.chmod(0o600)
        print(f"pinned local paths: {target}")
    print("Next: python setup/fetch_profile_refs.py " + " ".join(profiles))
    print("Then: python setup/build_retrieval_index.py " + " ".join(profiles))
    if failures:
        print("Missing assets: " + ", ".join(failures))
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
